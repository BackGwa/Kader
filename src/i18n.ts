const LOCALES: Record<string, Record<MessageKey, string>> = { en, ko, ja };

const messages = LOCALES[navigator.language.slice(0, 2).toLowerCase()] ?? en;

export function t(key: MessageKey, params: Record<string, string | number> = {}) {
  return messages[key].replace(/\{(\w+)\}/g, (match, name) => String(params[name] ?? match));
}
