const LOCALES: Record<string, Record<MessageKey, string>> = { ko, ja };

const messages = LOCALES[navigator.language.slice(0, 2).toLowerCase()] ?? en;

export function t(key: MessageKey, params?: Record<string, string | number>): string {
  return messages[key].replace(/\{(\w+)\}/g, (placeholder, name: string) =>
    String(params?.[name] ?? placeholder),
  );
}
